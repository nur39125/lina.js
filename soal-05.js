// Soal 5: Function

// Membuat function untuk menghitung luas persegi panjang
function hitungLuasPersegiPanjang(panjang, lebar) {
    let luas = panjang * lebar;

    return luas;
}

// Memanggil function
let hasil = hitungLuasPersegiPanjang(10, 5);

// Menampilkan hasil
console.log("=== LUAS PERSEGI PANJANG ===");
console.log("Panjang :", 10);
console.log("Lebar   :", 5);
console.log("Luas    :", hasil);